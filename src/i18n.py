def _detect_system_language() -> str:
    try:
        from PyQt6.QtCore import QLocale
        name = QLocale.system().name()  # e.g. "es_ES", "en_US"
        return "en" if name.lower().startswith("en") else "es"
    except Exception:
        return "es"


def set_language(code: str) -> None:
    global _LANG
    if code == "auto":
        code = _detect_system_language()
    _LANG = code if code in STRINGS else "es"


def get_language() -> str:
    return _LANG


def t(key: str, **kwargs: Any) -> str:
    table = STRINGS.get(_LANG, STRINGS["es"])
    text = table.get(key) or STRINGS["es"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
